const Node = require("../node");
const Cluster = require("../cluster");
const Simulator = require("../simulator");
const Network = require("../network");
const nodes = [new Node("A"), new Node("B"), new Node("C")];
const network = new Network();
const simulator = new Simulator(new Cluster(nodes), network);
console.log("\nSCENARIO: NETWORK PARTITION");
simulator.electLeader(nodes[0]);
simulator.replicate("before-partition");
console.log("\nPartition occurs: all network messages are dropped in this simplified model.");
network.partition();
simulator.heartbeat();
simulator.replicate("during-partition");
console.log("\nPartition repaired.");
network.repair();
simulator.heartbeat();
simulator.replicate("after-partition");
console.log("LESSON: A partition can stop progress; real Raft requires per-link partition modelling to demonstrate majority-side progress accurately.");
